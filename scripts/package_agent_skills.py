#!/usr/bin/env python3
"""Build the portable Agent Skills kit using the shared Rust release version."""

import argparse
import gzip
import hashlib
import io
import json
from pathlib import Path
import re
import subprocess
import sys
import tarfile
import tomllib


ROOT = Path(__file__).resolve().parent.parent
NAMES = ("rostfrei-develop-feature", "rostfrei-tracer")


def json_bytes(value):
    return (json.dumps(value, indent=2, sort_keys=True) + "\n").encode()


def release_metadata():
    subprocess.run([sys.executable, str(ROOT / "scripts/versions.py"), "check"], check=True)
    version = tomllib.loads((ROOT / "Cargo.toml").read_text())["workspace"]["package"]["version"]
    revision = subprocess.check_output(["git", "rev-parse", "HEAD"], cwd=ROOT, text=True).strip()
    dirty = bool(subprocess.check_output(["git", "status", "--porcelain"], cwd=ROOT, text=True).strip())
    catalog = (ROOT / "crates/rostfrei-tracer/src/catalog.rs").read_text()
    return {
        "kitVersion": 1,
        "frameworkVersion": version,
        "sourceRevision": revision,
        "sourceTreeDirty": dirty,
        "contracts": {
            "catalog": int(re.search(r"CATALOG_VERSION: u32 = (\d+)", catalog)[1]),
            "behavioralTest": 2,
            "messageSeries": 2,
            "fixture": 1,
        },
        "skills": list(NAMES),
    }


def generated_resources(release):
    """The same authoritative generated inputs for source discovery and archives."""
    resources = {}
    for name in NAMES:
        resources[f"{name}/references/release.json"] = json_bytes(release)
        resources[f"{name}/LICENSE"] = (ROOT / "LICENSE").read_bytes()
    resources["rostfrei-develop-feature/assets/behavioral-test-v2.schema.json"] = (
        ROOT / "crates/rostfrei-tracer/schema/behavioral-test-v2.schema.json"
    ).read_bytes()
    return resources


def prepare_source():
    resources = generated_resources(release_metadata())
    state = ROOT / ".agents/.generated-skill-resources.json"
    if state.is_symlink():
        raise ValueError(f"Preserving symlink: {state}")
    previous = json.loads(state.read_text()) if state.exists() else {}
    # Only refresh our previously generated bytes. Preflight all resources so an
    # edited or unowned file cannot cause a partial update of the other skill.
    for name, data in resources.items():
        path = ROOT / ".agents/skills" / name
        if path.is_symlink() or any(parent.is_symlink() for parent in path.parents):
            raise ValueError(f"Preserving symlink: {path}")
        if path.exists():
            existing = path.read_bytes()
            if existing != data and hashlib.sha256(existing).hexdigest() != previous.get(name):
                raise ValueError(f"Preserving modified/unowned resource: {path}; move it aside before preparing")
    for name, data in resources.items():
        path = ROOT / ".agents/skills" / name
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(data)
    state.write_bytes(json_bytes({name: hashlib.sha256(data).hexdigest() for name, data in resources.items()}))
    print("Prepared current source skill metadata, schema and licenses")


def build(output):
    release = release_metadata()
    version = release["frameworkVersion"]
    files = {
        "install.py": (ROOT / "scripts/install_agent_skills.py").read_bytes(),
        "README.md": (ROOT / "docs/agent-skills-install.md").read_bytes(),
        "QUALIFICATION.md": (ROOT / "docs/agent-skills-qualification.md").read_bytes(),
        "LICENSE": (ROOT / "LICENSE").read_bytes(),
        "release.json": json_bytes(release),
    }
    for name in NAMES:
        source = ROOT / ".agents/skills" / name
        if not (source / "SKILL.md").is_file():
            raise ValueError(f"Missing skill: {name}")
        for path in sorted(source.rglob("*")):
            if path.is_symlink():
                raise ValueError(f"Skill resources must be regular files: {path}")
            if path.is_file():
                files[f"skills/{name}/{path.relative_to(source).as_posix()}"] = path.read_bytes()
    files.update({f"skills/{name}": data for name, data in generated_resources(release).items()})
    files["manifest.json"] = json_bytes({
        "sha256": {name: hashlib.sha256(data).hexdigest() for name, data in sorted(files.items())},
    })
    output.mkdir(parents=True, exist_ok=True)
    stem = f"rostfrei-agent-skills-{version}"
    archive = output / f"{stem}.tar.gz"
    # Reproducible bytes for the same source state, irrespective of local mtimes,
    # checkout path, ownership, or archive output path.
    with archive.open("wb") as raw, gzip.GzipFile(fileobj=raw, mode="wb", filename="", mtime=0) as compressed:
        with tarfile.open(fileobj=compressed, mode="w") as bundle:
            for name, data in sorted(files.items()):
                info = tarfile.TarInfo(f"{stem}/{name}")
                info.size = len(data)
                info.mode = 0o644
                bundle.addfile(info, io.BytesIO(data))
    checksum = archive.with_suffix(archive.suffix + ".sha256")
    checksum.write_text(f"{hashlib.sha256(archive.read_bytes()).hexdigest()}  {archive.name}\n")
    print(archive)
    print(checksum)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    action = parser.add_mutually_exclusive_group(required=True)
    action.add_argument("--output", type=Path)
    action.add_argument("--prepare-source", action="store_true", help="refresh generated resources for repository-discovered skills")
    args = parser.parse_args()
    try:
        if args.prepare_source:
            prepare_source()
        else:
            build(args.output.resolve())
    except (OSError, ValueError, subprocess.CalledProcessError) as error:
        parser.exit(1, f"Kit build failed: {error}\n")


if __name__ == "__main__":
    main()
